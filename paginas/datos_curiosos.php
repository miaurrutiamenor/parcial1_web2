<h3>¿Sabías que...?</h3>
<ul>
    <li><strong>Referencias a videojuegos:</strong> El estilo visual y las batallas están profundamente inspirados en juegos como <em>The Legend of Zelda</em>, <em>Street Fighter</em> y <em>Super Mario Bros</em>.</li>
    <li><strong>Monedas de 10 peniques:</strong> Cada vez que un enemigo es derrotado, se desintegra convirtiéndose en monedas.</li>
    <li><strong>La Banda:</strong> La banda de Scott se llama "Sex Bob-omb", referencia directa a las "Bob-ombs" de Super Mario.</li>
</ul>

