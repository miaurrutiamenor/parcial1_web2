<h3>Preguntas Frecuentes (Q&A)</h3>
<p><strong>P: ¿En qué año se lanzó la película?</strong><br>
Fue estrenada en 2010 con el nombre <em>Scott Pilgrim vs. The World</em>, dirigida por Edgar Wright.</p>

<p><strong>P: ¿Cuántos tomos tiene el cómic original?</strong><br>
Consta de exactamente 6 volúmenes principales.</p>

<p><strong>P: ¿Cuántas ediciones diferentes tiene el comic?</strong><br>
Fue impresa en muchos formatos diferentes:</p>
<li><strong>Edición original en blanco y negro:</strong> Publicada por Oni Press entre 2004 y 2010 en formato de bolsillo pequeño (digest-sized)</li>
    <li><strong>Edición a todo color (Color Collection / Hardcover / Evil Editions):</strong>  Reimpresa y recoloreada por completo por Nathan Fairbairn entre 2012 y 2015, lanzada tanto en tomos dobles de tapa blanda como en ediciones de lujo de tapa dura (Hardcover).</li>
    <li><strong>Ediciones especiales de aniversario: </strong> Como la edición de caja por el 20.° aniversario en blanco y negro o en tapa dura recopilatoria.</li>

